import { prepareWorkflow } from './workflow.mjs';

// First editor bridge: local JSON trees, one execution per node. Merge, loops,
// waits and mocked HTTP keep using the CLI; extend after a native user case.
const localTypes = new Set(['code', 'set', 'filter', 'if', 'switch', 'noOp',
  'sort', 'limit', 'splitOut', 'aggregate', 'itemLists']
  .map(name => `n8n-nodes-base.${name}`));

function equalJson(a, b) {
  if (Object.is(a, b)) return true;
  if (!a || !b || typeof a !== 'object' || typeof b !== 'object') return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const keys = Object.keys(a);
  return keys.length === Object.keys(b).length &&
    keys.every(key => Object.hasOwn(b, key) && equalJson(a[key], b[key]));
}

function checkItems(items, assertion) {
  const label = `${assertion.node}: output ${assertion.output ?? 0}`;
  if (assertion.count !== undefined && items.length !== assertion.count)
    throw new Error(`n8n-check: ${label} expected ${assertion.count} items, got ${items.length}`);
  if (assertion.equals !== undefined) {
    const values = items.map((item, index) => {
      if (!assertion.pluck) return item.json;
      let value = item;
      for (const key of assertion.pluck.split('.')) {
        if (value === null || typeof value !== 'object' || !Object.hasOwn(value, key))
          throw new Error(`n8n-check: ${label} item ${index} is missing ${assertion.pluck}`);
        value = value[key];
      }
      return value;
    });
    if (!equalJson(values, assertion.equals))
      throw new Error(`n8n-check: ${label}${assertion.pluck ? ` ${assertion.pluck}` : ''} differs. Expected ${JSON.stringify(assertion.equals)}; got ${JSON.stringify(values)}`);
  }
  return { node: assertion.node, output: assertion.output ?? 0, count: items.length, passed: true };
}

export function editorTestWorkflow(source, spec) {
  if (!Array.isArray(spec?.mocks) || spec.mocks.length)
    throw new Error('Editor tests use local JSON nodes without HTTP mocks. Run this case with the CLI or Action.');
  if ((Array.isArray(source) ? source[0] : source)?.settings?.executionOrder === 'v0')
    throw new Error('Editor tests require v1 execution order. Keep the v0 case on the CLI or Action.');
  const workflow = prepareWorkflow(source, spec, 'http://127.0.0.1:1').workflow;
  const start = workflow.nodes[0];
  for (const node of workflow.nodes.slice(1)) {
    if (!localTypes.has(node.type))
      throw new Error(`Editor tests currently support local JSON transforms. "${node.name}" (${node.type}) needs the CLI for a self-contained workflow, or a separate integration environment for referenced workflows/resources.`);
  }
  const inlets = new Map();
  for (const types of Object.values(workflow.connections))
    for (const branches of Object.values(types))
      for (const branch of branches) for (const edge of branch) {
        inlets.set(edge.node, (inlets.get(edge.node) ?? 0) + 1);
        // A reachable cycle also has a second incoming edge at its entry;
        // prepareWorkflow separately rejects cycles through the fixture root.
        if (inlets.get(edge.node) > 1 || edge.index !== 0)
          throw new Error(`Editor tests need one incoming connection per node. "${edge.node}" uses the CLI or Action.`);
      }
  if (spec.assertions.some(assertion => assertion.node === spec.input.node))
    throw new Error('Select an executed downstream output, not the replaced fixture node.');
  let name = 'Check expected output';
  const names = new Set(workflow.nodes.map(node => node.name));
  while (names.has(name)) name += '_';
  const bottom = Math.max(...workflow.nodes.map(node => node.position?.[1] ?? 0));
  const jsCode = `// Generated by n8n-check. Fixed fixture, one run per node; leave this branch last.\n${equalJson}\n${checkItems}\nconst assertions = JSON.parse(${JSON.stringify(JSON.stringify(spec.assertions))});\nconst checks = assertions.map(assertion => {\n  const node = $(assertion.node);\n  const items = node.isExecuted ? node.all(assertion.output ?? 0, 0) : [];\n  return checkItems(items, assertion);\n});\nreturn [{ json: { status: 'passed', checks } }];`;
  workflow.nodes.push({ id: globalThis.crypto.randomUUID(), name,
    type: 'n8n-nodes-base.code', typeVersion: 2,
    position: [start.position[0], bottom + 240],
    parameters: { mode: 'runOnceForAllItems', jsCode } });
  // v1 is depth-first, top-to-bottom. This trigger branch runs even when the
  // tested branch returns zero items and all its downstream nodes are skipped.
  workflow.settings.executionOrder = 'v1';
  workflow.connections[start.name].main[0].push({ node: name, type: 'main', index: 0 });
  return workflow;
}
